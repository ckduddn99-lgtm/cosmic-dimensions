  const MAX_RECENT = 160;
  const SLOT = /\{([A-Z]{1,2})\}/g;
  function usable(t, ctx) { let ok = true; t.replace(SLOT, (m, k) => { if (ctx[k] === undefined || ctx[k] === null || ctx[k] === '') ok = false; return m; }); return ok; }
  function fill(t, ctx) { return t.replace(SLOT, (m, k) => String(ctx[k])); }

  /** 최근에 쓴 조각을 피해서 하나 고른다 (모두 최근이면 그중 가장 오래된 것) */
  function pickFresh(list, key, ctx, rnd, recent) {
    const cand = list.map((t, i) => [t, key + ':' + i]).filter(([t]) => usable(t, ctx));
    if (!cand.length) return null;
    const fresh = cand.filter(([, k]) => !recent.includes(k));
    const pool = fresh.length ? fresh : cand.sort((a, b) => recent.indexOf(a[1]) - recent.indexOf(b[1])).slice(0, 1);
    const [t, k] = pool[Math.floor(rnd() * pool.length)];
    const at = recent.indexOf(k);
    if (at >= 0) recent.splice(at, 1);
    recent.push(k);
    if (recent.length > MAX_RECENT) recent.splice(0, recent.length - MAX_RECENT);
    return t;
  }

  /** 성좌 c의 말: 부름말 + 본문 + 맺음말 */
  function star(c, topic, ctx, rnd, recent, opts = {}) {
    const core = pickFresh(STAR[topic] || [], 's.' + topic, ctx, rnd, recent);
    if (!core) return null;
    const call = opts.noCall || rnd() < 0.4 ? '' : pickFresh(CALL[c], 'c' + c, ctx, rnd, recent) + ' ';
    const tail = rnd() < 0.4 ? pickFresh(TAIL[c], 't' + c, ctx, rnd, recent) || '' : '';
    return fill(call + core + tail, ctx);
  }
  function star2(c, mood, ctx, rnd, recent) {
    const core = pickFresh(STAR2[mood], 's2.' + mood, ctx, rnd, recent);
    if (!core) return null;
    const tail = rnd() < 0.5 ? pickFresh(TAIL[c], 't' + c, ctx, rnd, recent) || '' : '';
    return fill(core + tail, ctx);
  }
  /** 사도의 말: 기질 말머리 + 태도별 본문 */
  function apostle(trait, topic, stance, ctx, rnd, recent) {
    const set = AP[topic];
    const list = Array.isArray(set) ? set : set && set[stance];
    const core = pickFresh(list || [], 'a.' + topic + '.' + stance, ctx, rnd, recent);
    if (!core) return null;
    const open = OPEN[trait] && rnd() < 0.35 ? pickFresh(OPEN[trait], 'o' + trait, ctx, rnd, recent) || '' : '';
    return fill(open + core, ctx);
  }
  function deed(kind, ctx, rnd, recent) {
    const t = pickFresh(DEED[kind] || [], 'd.' + kind, ctx, rnd, recent);
    return t ? fill(t, ctx) : null;
  }

